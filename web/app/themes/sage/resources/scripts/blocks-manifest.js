/**
 * Generate the block metadata manifest: resources/views/blocks/blocks-manifest.php.
 *
 * The manifest is a PHP file returning an array "<block folder> => <block.json
 * metadata>", the format WordPress reads with
 * wp_register_block_types_from_metadata_collection() (WP 6.8+): the blocks
 * are registered without globbing the folders and decoding every block.json on
 * each request (see app/blocks.php). It is what @wordpress/scripts
 * `build-blocks-manifest` produces, without the dependency.
 *
 * Only the folders with a block.json are listed, sorted by name. The values are
 * the decoded JSON as is (objects become associative arrays, like
 * json_decode(..., true)); the output follows the Pint laravel preset.
 *
 * The manifest is versioned: WordPress needs it at runtime, also where Node
 * is not available. Vite regenerates it at every build and, in dev, whenever a
 * block.json changes (vite.config.js); CI checks it is up to date (--check).
 *
 * Usage:
 *   npm run blocks:manifest        write the manifest
 *   npm run blocks:manifest:check  exit 1 if it is stale (--check), used in CI
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const themeDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export const blocksDir = path.join(themeDir, 'resources/views/blocks');
export const manifestPath = path.join(blocksDir, 'blocks-manifest.php');

const indent = (level) => '    '.repeat(level);

const phpString = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/**
 * PHP literal of a decoded JSON value.
 *
 * @param {unknown} value
 * @param {number} level
 * @returns {string}
 */
function toPhp(value, level) {
  if (value === null) {
    return 'null';
  }

  if (typeof value === 'boolean') {
    return value ? 'true' : 'false';
  }

  if (typeof value === 'number') {
    return Number.isInteger(value) ? String(value) : JSON.stringify(value);
  }

  if (typeof value === 'string') {
    return phpString(value);
  }

  const entries = Array.isArray(value)
    ? value.map((item) => [null, item])
    : Object.entries(/** @type {object} */ (value));

  if (entries.length === 0) {
    return '[]';
  }

  const lines = entries.map(([key, item]) => {
    const prefix = key === null ? '' : `${phpString(key)} => `;

    return `${indent(level + 1)}${prefix}${toPhp(item, level + 1)},`;
  });

  return `[\n${lines.join('\n')}\n${indent(level)}]`;
}

/**
 * Manifest source code for the current block.json files.
 *
 * @returns {string}
 */
export function buildBlocksManifest() {
  const metadata = {};

  const folders = fs
    .readdirSync(blocksDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  for (const folder of folders) {
    const file = path.join(blocksDir, folder, 'block.json');

    if (!fs.existsSync(file)) {
      continue;
    }

    try {
      metadata[folder] = JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (error) {
      throw new Error(`${path.relative(themeDir, file)}: ${error.message}`, { cause: error });
    }
  }

  return [
    '<?php',
    '',
    '// Generated by resources/scripts/blocks-manifest.js from the block.json files:',
    '// do not edit, run `npm run blocks:manifest` (Vite does it at build and in dev).',
    '',
    `return ${toPhp(metadata, 0)};`,
    '',
  ].join('\n');
}

/**
 * Write the manifest if its content changed.
 *
 * @returns {boolean} Whether the file was written.
 */
export function writeBlocksManifest() {
  const source = buildBlocksManifest();
  const current = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, 'utf8') : null;

  if (source === current) {
    return false;
  }

  fs.writeFileSync(manifestPath, source);

  return true;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const relative = path.relative(themeDir, manifestPath);

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, 'utf8') : null;

    if (current !== buildBlocksManifest()) {
      console.error(`${relative} is stale: run \`npm run blocks:manifest\` and commit it.`);
      process.exit(1);
    }

    console.log(`${relative} is up to date.`);
  } else {
    console.log(writeBlocksManifest() ? `${relative} written.` : `${relative} unchanged.`);
  }
}
